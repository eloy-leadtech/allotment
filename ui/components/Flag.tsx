/* Hand-drawn SVG flags, ported verbatim from the lab mockup (banderas.js).
   No external images: most flags are stripes, generated by tiny helpers; the
   ones with artwork are simplified to what reads at ~18px wide. Keyed by the
   Spanish country names that `Player.nacionalidad` carries ("España",
   "Rumanía", "República Checa"…), accents and case ignored. */

const W = 30;
const H = 20;

/** Vertical stripes of equal width. */
function V(...colors: string[]): string {
  const a = W / colors.length;
  return colors.map((col, i) => `<rect x="${i * a}" y="0" width="${a}" height="${H}" fill="${col}"/>`).join('');
}

/** Horizontal stripes of equal height. */
function Hz(...colors: string[]): string {
  const a = H / colors.length;
  return colors.map((col, i) => `<rect x="0" y="${i * a}" width="${W}" height="${a}" fill="${col}"/>`).join('');
}

/** Horizontal stripes with weights: HW([['#c', 2], ['#d', 1]]). */
function HW(list: Array<[string, number]>): string {
  const tot = list.reduce((s, x) => s + x[1], 0);
  let y = 0;
  return list
    .map(([col, w]) => {
      const h = (H * w) / tot;
      const r = `<rect x="0" y="${y}" width="${W}" height="${h}" fill="${col}"/>`;
      y += h;
      return r;
    })
    .join('');
}

/** Nordic cross: background, cross and (optionally) an inner fillet. */
function nordica(fondo: string, cruz: string, filete?: string): string {
  let s =
    `<rect width="${W}" height="${H}" fill="${fondo}"/>` +
    `<rect x="0" y="7.5" width="${W}" height="5" fill="${cruz}"/>` +
    `<rect x="9" y="0" width="5" height="${H}" fill="${cruz}"/>`;
  if (filete) {
    s +=
      `<rect x="0" y="9" width="${W}" height="2" fill="${filete}"/>` +
      `<rect x="10.5" y="0" width="2" height="${H}" fill="${filete}"/>`;
  }
  return s;
}

function estrella(cx: number, cy: number, r: number, col: string): string {
  const p: string[] = [];
  for (let i = 0; i < 5; i++) {
    const a1 = Math.PI * (-0.5 + i * 0.4);
    const a2 = a1 + Math.PI * 0.2;
    p.push(`${(cx + r * Math.cos(a1)).toFixed(2)},${(cy + r * Math.sin(a1)).toFixed(2)}`);
    p.push(`${(cx + r * 0.42 * Math.cos(a2)).toFixed(2)},${(cy + r * 0.42 * Math.sin(a2)).toFixed(2)}`);
  }
  return `<polygon points="${p.join(' ')}" fill="${col}"/>`;
}

/** Lowercase, accents and non-letters stripped: "República Checa" → "republicacheca". */
export function normalizeCountry(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z]/g, '');
}

