/** Whether a drawn flag exists for this country name. */
export function hasFlag(country: string | null | undefined): boolean {
  return country != null && normalizeCountry(country) in CATALOG;
}

interface FlagProps {
  /** Country name as the data carries it ("España", "República Checa"…). */
  country: string | null | undefined;
  className?: string;
}

/**
 * Little flag for the country, or a steel plate with its two initials when we
 * have no drawing (or no nationality at all).
 */
export function Flag({ country, className }: FlagProps) {
  const name = country ?? '';
  const body = name ? CATALOG[normalizeCountry(name)] : undefined;
  const cls = className ? `bandera ${className}` : 'bandera';
  return (
    <svg className={cls} viewBox="0 0 30 20" role="img" aria-label={name || 'Sin nacionalidad'}>
      <title>{name || 'Sin nacionalidad'}</title>
      {body ? (
        <g dangerouslySetInnerHTML={{ __html: body }} />
      ) : (
        <>
          <rect width="30" height="20" fill="#2A4478" />
          <text x="15" y="14.5" textAnchor="middle" fontFamily="sans-serif" fontSize="11" fill="#B8C8E8">
            {(name || '?').slice(0, 2).toUpperCase()}
          </text>
        </>
      )}
      <rect x=".5" y=".5" width="29" height="19" fill="none" stroke="rgba(0,0,0,.45)" />
    </svg>
  );
}
